// Checks that everything documented as public in the API doc files exists in the code. bin/typecheck
// writes a probe file for tsc that indexes the global `Up` interface (the type of `window.up`) and
// `UpEventMap` with every public entry's name, one line per entry:
//
//   type P2 = Up['Request']['prototype']['abort'] // src/unpoly/network/request.md:42
//
// and translates tsc's errors on those lines back to the doc file, like
//
//   src/unpoly/network/request.md(42,11): error TS2339: Documented as up.Request#abort, but `Up['Request']['prototype']` has no `abort`.
//
// Only an entry's declaration (its first @function, @property, @class line …) and its name are
// probed: what it documents must exist, its parameters and types are not compared. The probe
// never checks the other direction, so code may have public API without docs.
//
// Probed:
//   @function up.a.b, @function up.A#b   Up['a']['b'] must be a function
//   @property up.a.b, @property up.A#b   Up['a']['b'], Up['A']['prototype']['b'] must exist
//   @namespace up.a, @class up.A         Up['a'], Up['A'] must exist
//   @constructor up.A                    Up['A'] must be a class
//   @event up:a:b                        UpEventMap['up:a:b'] must exist
//
// Skipped:
//   - entries marked @internal,
//   - what has no type: selectors and attributes ([up-follow]), headers, cookies, pages and partials,
//   - names outside `window.up`, like the List concept (util/list.md).
//
// The core probe covers src/unpoly/ and runs in the core check (tsconfig.core.json), which leaves
// out unpoly-migrate, so a core entry can't pass on something only unpoly-migrate declares. The
// migrate probe covers src/unpoly-migrate/ against everything, unpoly-migrate's declarations
// included (tsconfig.json).
import fs from 'node:fs'
import path from 'node:path'
import { PROJECT_ROOT } from '../build/build_status.mjs'
import { codeLines, docFiles, parseDocFile } from './doc_file.mjs'

// The directives that declare what an entry documents. The first one in an entry counts.
const DECLARATION = /^@(class|namespace|page|function|selector|event|property|constructor|header|cookie|partial)[ \t]+(\S+)/
const INTERNAL = /^@internal\b/

// What tsc must accept for each kind we probe, as the text around the probed type.
const PROBES = {
  function: ['Parameters<', '>'],
  property: ['', ''],
  namespace: ['', ''],
  class: ['', ''],
  constructor: ['ConstructorParameters<', '>'],
  event: ['', ''],
}

// The public entries of a doc file that we can probe ({ kind, name, root, keys, line, column }),
// with the line and column of the name in their declaration.
export function declarations(text) {
  return parseDocFile(text).entries.flatMap((entry) => {
    let { code } = codeLines(entry.lines)
    let directives = entry.lines.map((text, index) => ({ text, line: entry.line + index })).filter((_, index) => !code.has(index))
    if (directives.some(({ text }) => INTERNAL.test(text))) return []
    let declaration = directives.find(({ text }) => DECLARATION.test(text))
    if (!declaration) return []
    let [, kind, name] = declaration.text.match(DECLARATION)
    let probed = probePath(kind, name)
    if (!probed) return []
    return [{ kind, name, ...probed, line: declaration.line, column: kind.length + 3 }]
  })
}

// `up.Request#abort` → Up['Request']['prototype']['abort']. Undefined for what we don't probe.
function probePath(kind, name) {
  if (!PROBES[kind]) return
  if (kind === 'event') return name.startsWith('up:') ? { root: 'UpEventMap', keys: [name] } : undefined
  let [first, ...keys] = name.replace(/\(\)$/, '').replace(/#/g, '.prototype.').split('.')
  if (first !== 'up' || !keys.length) return
  return { root: 'Up', keys }
}

// The source of a probe file for the given probes ({ file, ...declaration }), and the number of
// lines before the first probe. `srcPath` is the path from the probe file to src/.
export function probeSource(probes, srcPath) {
  let header = [
    `// Generated by bin/typecheck from the API doc files (tooling/docs/api_probe.mjs). Don't edit.`,
    `import type { Up } from '${srcPath}/unpoly.js'`,
    `import type { UpEventMap } from '${srcPath}/unpoly/event.js'`,
  ]
  let lines = probes.map((probe, index) => probeLine(probe, index).text)
  return { source: [...header, ...lines, ''].join('\n'), headerLines: header.length }
}

// The probe's line, and the column at which each key of its expression starts (as tsc counts them).
function probeLine({ kind, root, keys, file, line }, index) {
  let [open, close] = PROBES[kind]
  let before = `type P${index + 1} = ${open}`
  let expr = root
  let columns = keys.map((key) => {
    let column = before.length + expr.length + 2
    expr += `[${quote(key)}]`
    return column
  })
  return { text: `${before}${expr}${close} // ${file}:${line}`, columns }
}

function quote(key) {
  return `'${key.replace(/[\\']/g, '\\$&')}'`
}

// All probes, split into the core probe (src/unpoly/) and the migrate probe (src/unpoly-migrate/),
// each with paths from the project root.
export function collectProbes(root = PROJECT_ROOT) {
  let probes = { core: [], migrate: [] }
  for (let file of docFiles(path.join(root, 'src'))) {
    let relative = path.relative(root, file)
    let group = relative.startsWith(`src${path.sep}unpoly-migrate${path.sep}`) ? probes.migrate : probes.core
    for (let declaration of declarations(fs.readFileSync(file, 'utf8'))) group.push({ file: relative, ...declaration })
  }
  return probes
}

// Translates a block of tsc's plain output (`--pretty false`) for an error in the probe file into
// a block for the doc file. Returns undefined for a block that isn't about a probe line.
export function translateError(lines, probes, headerLines) {
  let match = lines[0].match(/^\S+\((\d+),(\d+)\): error (TS\d+): (.*)$/)
  if (!match) return
  let [, probeLineNumber, column, code, message] = match
  let index = Number(probeLineNumber) - headerLines - 1
  let probe = probes[index]
  if (!probe) return
  let { columns } = probeLine(probe, index)
  let at = `${probe.file}(${probe.line},${probe.column}): error ${code}: Documented as ${probe.name}, but `
  let expr = (keys) => probe.root + keys.map((key) => `[${quote(key)}]`).join('')
  let keyIndex = columns.indexOf(Number(column))
  if (code === 'TS2339' && keyIndex >= 0) {
    return [`${at}\`${expr(probe.keys.slice(0, keyIndex))}\` has no \`${probe.keys[keyIndex]}\`.`]
  } else if (code === 'TS2344' && probe.kind === 'function') {
    return [`${at}\`${expr(probe.keys)}\` is not a function.`]
  } else if (code === 'TS2344' && probe.kind === 'constructor') {
    return [`${at}\`${expr(probe.keys)}\` is not a class.`]
  } else {
    return [`${at}its probe fails: ${message}`, ...lines.slice(1)]
  }
}
